import { NextRequest, NextResponse } from "next/server";
import { createClient } from "@/lib/supabase/server";

export async function GET(req: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const supabase = await createClient();
  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return NextResponse.json({ error: "Unauthorized" }, { status: 401 });

  const { data: doc } = await supabase
    .from("documents")
    .select("*, similarity_results(*), ai_writing_reports(*), citation_reports(*), grammar_reports(*)")
    .eq("id", id)
    .eq("user_id", user.id)
    .single();

  if (!doc) return NextResponse.json({ error: "Document not found" }, { status: 404 });
  if (doc.status !== "completed") return NextResponse.json({ error: "Report not yet complete" }, { status: 409 });

  // Generate a simple HTML report as the PDF download
  // A production implementation would use Puppeteer or a PDF library
  const reportNumber = `TA-${Date.now().toString(36).toUpperCase()}`;
  const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<title>TrueAuthor Originality Report: ${doc.title ?? "Document"}</title>
<style>
  body { font-family: Arial, sans-serif; color: #263449; margin: 0; padding: 2rem; }
  h1 { color: #102A43; font-size: 1.5rem; margin-bottom: 0.5rem; }
  h2 { color: #155EEF; font-size: 1.1rem; margin: 1.5rem 0 0.5rem; }
  .meta { color: #64748B; font-size: 0.875rem; margin-bottom: 1.5rem; }
  .score { font-size: 2.5rem; font-weight: 800; color: ${(doc.similarity_score ?? 0) > 30 ? "#D97706" : "#16A34A"}; }
  .notice { background: #FFF7F5; border: 1px solid #FFD6CF; border-radius: 6px; padding: 0.75rem 1rem; font-size: 0.875rem; color: #7C3A30; margin-bottom: 1rem; }
  table { width: 100%; border-collapse: collapse; }
  th, td { padding: 0.5rem 0.75rem; text-align: left; border-bottom: 1px solid #E2EAF2; font-size: 0.875rem; }
  th { background: #F5F8FC; font-weight: 700; }
  .footer { margin-top: 3rem; padding-top: 1rem; border-top: 1px solid #D1DCF0; font-size: 0.75rem; color: #94A3B8; }
</style>
</head>
<body>
<h1>TrueAuthor Originality Report</h1>
<div class="meta">
  <strong>Document:</strong> ${doc.title ?? "Untitled"}<br/>
  <strong>Report reference:</strong> ${reportNumber}<br/>
  <strong>Analysis date:</strong> ${new Date().toLocaleDateString("en-GB", { weekday: "long", day: "numeric", month: "long", year: "numeric" })}<br/>
  <strong>Analysed by:</strong> ${user.email}
</div>

<h2>Similarity Score</h2>
<div class="score">${doc.similarity_score ?? 0}%</div>
<p>Similarity identified against available comparison sources.</p>
<div class="notice">
  A similarity score identifies text that resembles sources in the comparison database. A similarity match is not a confirmed plagiarism finding. Similarity may arise from common academic phrases, properly cited quotations or coincidental phrasing. This report does not constitute a formal academic misconduct finding.
</div>

${doc.ai_writing_reports ? `
<h2>AI Writing Indicators</h2>
<p><strong>Overall indicator:</strong> ${(doc.ai_writing_reports as { overall_indicator?: string })?.overall_indicator ?? "—"} (Confidence: ${(doc.ai_writing_reports as { confidence?: string })?.confidence ?? "—"})</p>
<div class="notice">AI writing analysis is probabilistic and subject to false positives and false negatives. These results are contextual observations, not evidence of misconduct.</div>
` : ""}

${doc.citation_reports ? `
<h2>Citation Review</h2>
<p>${(doc.citation_reports as { summary?: string })?.summary ?? ""}</p>
` : ""}

${doc.grammar_reports ? `
<h2>Grammar Analysis</h2>
<p>${(doc.grammar_reports as { summary?: string })?.summary ?? ""}</p>
` : ""}

<div class="footer">
  &copy; 2026 TrueAuthor &mdash; Original Work. Authentic Thinking. Trusted Results.<br/>
  This report is generated by TrueAuthor and is provided for informational purposes only.
</div>
</body>
</html>`;

  return new NextResponse(html, {
    headers: {
      "Content-Type": "text/html",
      "Content-Disposition": `attachment; filename="TrueAuthor-Report-${reportNumber}.html"`,
    },
  });
}
